#!/usr/bin/env python3
"""Generate the GB2312 text table for the TJC serial screen.

Input : firmware/spark_garage_lvgl/applications/hmi/hmi_text.txt (UTF-8)
Output: firmware/spark_garage_lvgl/applications/hmi/hmi_text.h
        docs/串口屏界面_v1/字库字符集.txt

The screen project uses GB2312, while the firmware sources are UTF-8, so the
strings are emitted as hex escapes. Run from anywhere: py tools/gen_hmi_text.py
"""
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "firmware", "spark_garage_lvgl", "applications", "hmi", "hmi_text.txt")
OUT_H = os.path.join(ROOT, "firmware", "spark_garage_lvgl", "applications", "hmi", "hmi_text.h")
OUT_CHARS = os.path.join(ROOT, "docs", "串口屏界面_v1", "字库字符集.txt")

STEP_ORDER = [
    "NONE", "FETCH_TRAY", "PULL_FROM_DOCK", "ROTATE_TO_BAY", "LIFT_TO_LAYER", "ENGAGE",
    "PUSH_INTO_BAY", "FORK_RETRACT", "PRESET_TRAY", "RETURN_DOCK_TRAY", "PULL_FROM_BAY",
    "ROTATE_TO_DOCK", "PUSH_TO_DOCK", "HOMING",
]


def parse(path):
    sections, cur = {}, None
    with io.open(path, encoding="utf-8") as f:
        for n, raw in enumerate(f, 1):
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            if line.startswith("[") and line.endswith("]"):
                cur = line[1:-1]
                sections[cur] = []
                continue
            if cur is None:
                sys.exit("%s:%d: text before the first [section]" % (path, n))
            if cur == "screen":
                sections[cur].append((None, line))
                continue
            if "=" not in line:
                sys.exit("%s:%d: expected 'key = text'" % (path, n))
            key, text = [s.strip() for s in line.split("=", 1)]
            if '"' in text:
                sys.exit("%s:%d: double quote is not allowed in screen text" % (path, n))
            sections[cur].append((key, text))
    return sections


def gb(ch):
    """Encode one character to GB2312 bytes, or None if it is outside GB2312.

    Python's gb2312 codec maps the middle dot differently from Windows, so encode
    with gbk and accept only the GB2312 byte range (lead A1..F7, trail A1..FE).
    """
    if ord(ch) < 0x80:
        return ch.encode("ascii")
    try:
        data = ch.encode("gbk")
    except UnicodeEncodeError:
        return None
    if len(data) == 2 and 0xA1 <= data[0] <= 0xF7 and 0xA1 <= data[1] <= 0xFE:
        return data
    return None


def c_str(text, where):
    data = b""
    for ch in text:
        enc = gb(ch)
        if enc is None:
            sys.exit("%s: character %r is not in GB2312" % (where, ch))
        data += enc
    return '"' + "".join("\\x%02X" % b for b in data) + '"'


def main():
    sec = parse(SRC)
    for need in ("dir", "step", "fmt", "fault", "screen"):
        if need not in sec:
            sys.exit("missing section [%s]" % need)

    dirs = dict(sec["dir"])
    steps = dict(sec["step"])
    if sorted(dirs) != [str(i) for i in range(8)]:
        sys.exit("[dir] must define 0..7")
    missing = [s for s in STEP_ORDER if s not in steps]
    extra = [s for s in steps if s not in STEP_ORDER]
    if missing or extra:
        sys.exit("[step] mismatch with enum ui_step: missing %s, unknown %s" % (missing, extra))

    o = []
    o.append("/* Generated by tools/gen_hmi_text.py from hmi_text.txt. DO NOT EDIT. */")
    o.append("/* Strings are GB2312 bytes for the TJC screen. */")
    o.append("#ifndef HMI_TEXT_H\n#define HMI_TEXT_H\n")
    o.append("#include <stdint.h>\n")
    o.append("static const char *const k_hmi_dir[8] = {")
    for i in range(8):
        o.append("    %s, /* %s */" % (c_str(dirs[str(i)], "dir %d" % i), dirs[str(i)]))
    o.append("};\n")
    o.append("/* Indexed by enum ui_step. */")
    o.append("static const char *const k_hmi_step[%d] = {" % len(STEP_ORDER))
    for name in STEP_ORDER:
        o.append("    %s, /* %s: %s */" % (c_str(steps[name], "step " + name), name, steps[name]))
    o.append("};\n")
    for key, text in sec["fmt"]:
        o.append("#define HMI_TXT_%s %s /* %s */" % (key, c_str(text, "fmt " + key), text))
    o.append("")
    o.append("struct hmi_fault_text { uint8_t code; const char *title; const char *hint; };")
    o.append("/* The entry with code 0 is the fallback and must stay last. */")
    o.append("static const struct hmi_fault_text k_hmi_fault[] = {")
    faults = []
    for key, text in sec["fault"]:
        if "|" not in text:
            sys.exit("[fault] %s: expected 'title | hint'" % key)
        title, hint = [s.strip() for s in text.split("|", 1)]
        faults.append((int(key), title, hint))
    faults.sort(key=lambda f: (f[0] == 0, f[0]))
    if not faults or faults[-1][0] != 0:
        sys.exit("[fault] needs a fallback entry with code 0")
    for code, title, hint in faults:
        o.append("    { %d, %s,\n      %s }, /* %s */" % (
            code, c_str(title, "fault %d" % code), c_str(hint, "fault %d" % code), title))
    o.append("};\n")
    o.append("#endif /* HMI_TEXT_H */\n")
    # String literals are pure ASCII escapes; only the comments are UTF-8.
    with io.open(OUT_H, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(o))

    chars = set()
    for items in sec.values():
        for _, text in items:
            chars.update(ch for ch in text.replace("\\r", "") if ord(ch) > 0x7F)
    for ch in chars:
        if gb(ch) is None:
            sys.exit("character %r is not in GB2312" % ch)
    ordered = "".join(sorted(chars, key=gb))
    os.makedirs(os.path.dirname(OUT_CHARS), exist_ok=True)
    with io.open(OUT_CHARS, "w", encoding="utf-8", newline="\n") as f:
        f.write(ordered + "\n")
    print("wrote %s" % os.path.relpath(OUT_H, ROOT))
    print("wrote %s (%d characters)" % (os.path.relpath(OUT_CHARS, ROOT), len(ordered)))


if __name__ == "__main__":
    main()
